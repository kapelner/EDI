# v1.0.6-TODO-98: the smoothed BRT adds N(0, sd(y)/sqrt(n)) noise to each resampled
# exact response. Under left-/interval-censoring a censored subject's y is NA, so the
# noise reached exact times only, the bandwidth came from the exact times alone (1.0 in
# raw time units when there are none), and additive noise on positive times breaks the
# 0 lower bound of a left-censored interval. There is no smoothed-bootstrap theory for
# interval-censored data to fall back on, so smoothing is refused there.
rand_bootstrap_smoothing_has_general_censoring <- function(inf_obj){
	isTRUE(inf_obj$.__enclos_env__$private$has_general_censoring)
}

rand_bootstrap_smoothing_supported <- function(inf_obj, response_type){
	if (rand_bootstrap_smoothing_has_general_censoring(inf_obj)) return(FALSE)
	if (!response_type %in% c("incidence", "ordinal", "proportion")) return(TRUE)
	# Real-valued location statistics can smooth their statistic even when the
	# recorded response is coded categorically. Categorical model refits cannot.
	if (inherits(inf_obj, c("InferenceOrdinalRidit", "InferenceOrdinalJonckheereTerpstraTest"))) return(FALSE)
	inf_obj$.__enclos_env__$private$has_private_method("compute_fast_rand_bootstrap_distr")
}

assert_rand_bootstrap_smoothing_supported <- function(inf_obj, response_type){
	if (!rand_bootstrap_smoothing_supported(inf_obj, response_type)) {
		if (rand_bootstrap_smoothing_has_general_censoring(inf_obj)) {
			stop("Smoothed randomization bootstrap is not supported for left- or interval-censored ",
			     "survival responses in ", class(inf_obj)[1L], " (censored subjects have no exact ",
			     "time to smooth); use type = 'percentile'.", call. = FALSE)
		}
		stop("Smoothed randomization bootstrap is not supported for ", response_type,
		     " responses in ", class(inf_obj)[1L], "; use type = 'percentile'.", call. = FALSE)
	}
}

#' Bootstrap Randomization Test Inference
#'
#' Abstract class implementing the bootstrap randomization test (BRT), a hybrid of the
#' nonparametric bootstrap and the randomization test of Fisher's sharp null. This
#' construction is inspired by Kallus, N. (2018), "Optimal a priori balance in the design
#' of controlled experiments," \emph{Journal of the Royal Statistical Society: Series B},
#' 80(1), 85-112, Section 5 ("Algorithms for inference"), Algorithm 4 -- see
#' \code{@references} below for the full attribution and what EDI's implementation adds
#' beyond it.
#'
#' @description
#' Each of the \code{B} null draws is generated by (1) resampling \code{n} subject rows
#' \emph{with replacement} from the observed data and (2) drawing one fresh assignment
#' vector \code{w} from the actual experimental design run on the resampled covariates.
#' The test statistic computed on each such draw forms a null distribution against which
#' the observed statistic (actual data, actual \code{w}) is compared.
#'
#' @section Design restriction:
#' Like the nonparametric bootstrap, the randomization bootstrap resamples subject rows
#' with replacement, so it is not supported for \code{DesignSeqOneByOne} designs and
#' their subclasses (including the KK matching-on-the-fly designs), except the concrete
#' \code{DesignSeqOneByOneBernoulli} class. Its validity on adaptive sequential designs
#' is unproven. Calling a restricted method reports that the method is not supported,
#' and \code{supports()} returns \code{FALSE} for \code{randomization_bootstrap} and
#' \code{randomization_bootstrap_ci}. KK estimators still offer it on the fixed
#' matched-pairs design \code{DesignFixedBinaryMatch}. Where the Details below
#' mention the matching-on-the-fly designs (\code{DesignSeqOneByOneKK14}/\code{KK21}/
#' \code{KK21stepwise}), they describe how the construction would apply in
#' principle; in this package the BRT does not run on those designs, and the
#' pair-aware resampling applies to \code{DesignFixedBinaryMatch}.
#'
#' @details
#' \strong{Motivating heuristic: the sharp null makes the science table fully known.}
#' Under Fisher's sharp null \eqn{H_0: y_i(0) = y_i(1) = y_i} for all \eqn{i}, the observed
#' outcome is the outcome regardless of assignment, so each observed row \eqn{(x_i, y_i)}
#' is a complete description of that subject: it can be paired with any \eqn{w} and the
#' outcome is still correct. Resampling rows and drawing a fresh \eqn{w} therefore
#' simulates an entire new experiment — new subjects from \eqn{\hat{F}_n} (the empirical
#' distribution of subjects), new assignment from the true, known assignment mechanism —
#' under the assumption that outcomes do not respond to treatment. Both simulation
#' ingredients are faithful to the real data-generating process under \eqn{H_0}: the
#' assignment mechanism is exact (drawn from the actual design, including sequential
#' covariate-dependent designs, since the design depends only on the covariates), and the
#' subject distribution is approximately right by the usual bootstrap argument
#' \eqn{\hat{F}_n \to F}. \emph{This is a motivating heuristic, not a proof} — see "Known
#' limitations and open theoretical question" below for exactly where it stops short of
#' establishing asymptotic validity, and why. If \eqn{H_0} is false, the construction
#' \emph{still} generates the null distribution (it forcibly treats \eqn{y} as invariant to
#' \eqn{w}) while the observed statistic drifts into the tail — that asymmetry is the
#' intended source of power, independent of the open validity question below.
#'
#' \strong{Why this outgrew its original motivation.} This construction was originally
#' implemented for a narrow reason: it works even when \eqn{w} is deterministic or
#' near-deterministic, exactly the degenerate case Kallus (2018) needed it for (see
#' \code{@references}). It turns out to be useful well beyond that: (1) it is
#' design-agnostic for free, since it calls \code{draw_ws_according_to_design()} on the
#' resampled data rather than enumerating a permutation space -- for the matching-on-the-fly
#' designs (\code{DesignSeqOneByOneKK14}/\code{KK21}/\code{KK21stepwise}), that permutation
#' space depends on the whole sequential arrival/matching history and has no closed form
#' worth enumerating, so a classic randomization test would need bespoke combinatorics this
#' construction avoids entirely; (2) it generalizes the inferential target from
#' finite-population (conditional on exactly these \eqn{n} subjects) to superpopulation,
#' independent of the degenerate-design motivation; (3) it inherits the rest of the
#' inference machinery (CI inversion, the estimand/testing-type axes) automatically by
#' living in the same class hierarchy as everything else, rather than being a bolted-on
#' special case usable only for the one scenario that motivated it.
#'
#' \strong{How it differs from the pure randomization test.} The classic randomization
#' test conditions on the realized sample (the "science table") and is exact for any
#' \eqn{n}. The BRT is unconditional: it targets the distribution of the statistic over
#' both subject sampling and randomization, and the null tested is the compound "sharp
#' null AND subjects are i.i.d. draws from \eqn{F}". Exactness is traded for a
#' population-level (superpopulation) interpretation. Equivalently, the BRT is a
#' parametric bootstrap test whose "parameter" is the pair (\eqn{F}, design): the design
#' part is known exactly, \eqn{F} is plugged in via \eqn{\hat{F}_n}, and the sharp null is
#' precisely what makes \eqn{\hat{F}_n} estimable from one arm-agnostic dataset. The pure
#' randomization test is the special case where \eqn{F} is conditioned away.
#'
#' \strong{Known limitations and open theoretical question: asymptotic validity is not
#' proven, for two distinct, identifiable reasons.} Kallus (2018) himself states that
#' asymptotic validity of this bootstrap test is "believed" rather than established, and
#' explicitly calls it an open question. EDI's implementation does not resolve that
#' question; the two specific gaps are:
#' \enumerate{
#'   \item \strong{Glivenko-Cantelli is not bootstrap consistency.} The motivating heuristic
#'     above leans on \eqn{\hat{F}_n \to F} to justify substituting a bootstrap resample for
#'     a genuinely fresh i.i.d. draw from \eqn{F}. But \eqn{\hat{F}_n \to F} (uniform
#'     convergence of the empirical CDF, a Glivenko-Cantelli statement) is a claim about the
#'     empirical distribution itself; it is \emph{not} the same as consistency of the
#'     bootstrap, i.e. convergence of the \emph{sampling distribution of the test statistic}
#'     computed under resampling from \eqn{\hat{F}_n} to the statistic's true sampling
#'     distribution under \eqn{F}. That second, load-bearing claim is well known to require
#'     statistic-specific regularity conditions (smoothness/Hadamard differentiability of
#'     the statistic as a functional of the empirical process, adequate moment conditions,
#'     etc. — the classical Bickel-Freedman-type distinction) and is known to fail for some
#'     statistics even when \eqn{\hat{F}_n \to F} holds trivially (e.g. non-smooth
#'     statistics, extreme-value/max-type statistics, heavy-tailed distributions without
#'     enough moments, non-regular estimators). No such regularity condition is verified,
#'     case by case, for the estimators this class is composed into.
#'   \item \strong{The naive version of this concern is already mitigated by design; a
#'     narrower residual question remains open.} A naive i.i.d. row bootstrap would create
#'     exact duplicate rows that never occur in real data, and for a design whose assignment
#'     mechanism depends on the joint covariate configuration of the whole sample — exactly
#'     what EDI's matching-on-the-fly designs
#'     (\code{DesignSeqOneByOneKK14}/\code{KK21}/\code{KK21stepwise}) and fixed matched-pair
#'     designs (\code{DesignFixedBinaryMatch}) do — those artificial exact ties would
#'     fabricate zero-distance ("perfect") matches that a genuinely fresh sample from
#'     \eqn{F} would essentially never produce. \strong{This package does not resample rows
#'     i.i.d. for matching-capable designs.} \code{DesignMatchingAbstract$draw_bootstrap_indices()}
#'     (\code{design_matching_abstract.R}), inherited by every matching-capable design,
#'     dispatches to a pair-aware resampler
#'     (\code{private$draw_matching_bootstrap_indices()}) that resamples reservoir subjects
#'     i.i.d. \emph{and matched pairs as intact units} — preserving each pair's true,
#'     historically realized within-pair covariate distance rather than fabricating an
#'     artificial zero-distance one. This is the correct fix for the naive-duplicate-row
#'     concern, and it is already active for every BRT draw on a supported
#'     matching-capable design (currently \code{DesignFixedBinaryMatch}; see
#'     "Design restriction") (\code{InferenceRandBootstrap} inherits \code{bootstrap_sample_indices()} from the
#'     same chain, so no separate wiring is needed). \strong{What remains open, narrower
#'     than the naive concern above:} reservoir subjects are still resampled i.i.d.
#'     independently of the intact pairs, so a single reservoir subject can still appear
#'     more than once in one bootstrap draw; whether two duplicate copies of the same
#'     original reservoir subject can subsequently be matched to each other by the
#'     re-run sequential matching algorithm (fabricating a same-subject zero-distance pair
#'     as a second-order effect, distinct from the naive first-order concern this
#'     mitigation addresses) has not been analyzed in this package. This is a narrower,
#'     unquantified residual question, not a demonstrated bias.
#' }
#' \strong{Status: point 1 above is a documented open theoretical question, not a settled
#' result; point 2's naive form is mitigated by the pair-aware resampler described above,
#' with only the narrower residual question left open.} Neither this package nor Kallus
#' (2018) supplies a general proof of asymptotic validity covering point 1; both explicitly
#' flag it as unresolved rather than claiming a proof. Treat the p-values and confidence
#' intervals from this class as resting on a well-motivated but unproven asymptotic
#' argument. A rigorous asymptotic proof (or a demonstrated counterexample) remains future
#' work.
#'
#' \strong{Other implementation notes.} (1) For sequential designs the bootstrap sample
#' needs an arrival order; the i.i.d. resampling order plays that role, matching the
#' i.i.d.-arrivals assumption of the KK designs. (2) Studentization is not needed for the
#' motivating heuristic above but, as with any bootstrap test, an asymptotically pivotal
#' statistic improves the level's rate of convergence where the construction is valid.
#'
#' Users do not instantiate this class directly: every concrete inference class in the
#' package inherits from it, so its methods (\code{compute_rand_bootstrap_two_sided_pval},
#' \code{approximate_rand_bootstrap_distribution_beta_hat_T}) are available on any
#' inference object. See \code{\link{InferenceRandBootstrapCI}} for the companion
#' confidence interval.
#'
#' @references Kallus, N. (2018), "Optimal a priori balance in the design of controlled
#'   experiments," \emph{Journal of the Royal Statistical Society: Series B}, 80(1), 85-112,
#'   Section 5 ("Algorithms for inference"), Algorithm 4 -- the nearest prior appearance of
#'   this exact construction (resample subjects, then redraw one fresh assignment from the
#'   design on the resampled covariates), introduced there for the degenerate case of his a
#'   priori balancing designs (PSODs), where a design can admit only one or very few
#'   distinct treatment permutations, so the classic Fisher randomization test has no power
#'   (it always returns p-value 1). Kallus himself cites Efron, B. and Tibshirani, R.
#'   (1993), \emph{An Introduction to the Bootstrap}, Chapman & Hall, for the bootstrap
#'   ingredient, and Good, P. (2005), \emph{Permutation, Parametric and Bootstrap Tests of
#'   Hypotheses}, Springer, for the test/confidence-interval duality used to invert his
#'   Algorithm 4 into intervals -- and states asymptotic validity of the bootstrap test as
#'   an open question, not a proven result (see "Known limitations and open theoretical
#'   question" above, which this package inherits and extends with the matching-design-
#'   specific failure mode). EDI's contribution beyond Algorithm 4 is generalizing the
#'   construction to arbitrary designs (fixed and sequential, including the matching-on-
#'   the-fly family) and response types, and pairing it with a confidence-interval
#'   inversion (\code{\link{InferenceRandBootstrapCI}}); it does not resolve the open
#'   validity question.
#' @template rand-mc-pvalue-references
#'
#' @examples
#' seq_des = DesignSeqOneByOneBernoulli$new(n = 20, response_type = "continuous")
#' for (i in 1:20) {
#'   seq_des$add_one_subject_to_experiment_and_assign(data.frame(x1 = rnorm(1), x2 = rnorm(1)))
#' }
#' seq_des$add_all_subject_responses(rnorm(20))
#' seq_des_inf = InferenceAllSimpleAverageDiff$new(seq_des)
#' seq_des_inf$compute_rand_bootstrap_two_sided_pval(B = 101)
#' @keywords internal
InferenceRandBootstrap = R6::R6Class("InferenceRandBootstrap",
	lock_objects = FALSE,
	inherit = InferenceNonParamBootstrap,
	public = list(
		# 2026-08-19 (inference_suite_inspect.md audit): real introspection
		# accessor, same rationale as NonparametricBootstrap/BayesianBootstrap's
		# identical pairs. See RandomizationBootstrapCI's
		# get_supported_rand_bootstrap_ci_types() for the CI side.
		#' @description Returns the \code{type} values
		#'   \code{compute_rand_bootstrap_two_sided_pval()} accepts.
		get_supported_rand_bootstrap_pval_types = function(){
			types = private$rand_bootstrap_pval_types
			if (!rand_bootstrap_smoothing_supported(self, private$des_obj_priv_int$response_type)) types = setdiff(types, "smoothed")
			types
		},
		#' @description Computes the bootstrap randomization null distribution of the test
		#'   statistic under Fisher's sharp null (shifted by \code{delta}): each draw resamples
		#'   subject rows with replacement and draws one fresh assignment vector from the design.
		#'
		#' @param B  					Number of bootstrap randomization draws. Default 501.
		#' @param delta  				The null treatment effect (on the \code{transform_responses}
		#'   scale). Default 0.
		#' @param transform_responses  Type of response transformation used to impose the
		#'   sharp null shift for nonzero \code{delta}. Default "none".
		#' @param show_progress  		A flag indicating whether a progress bar should be displayed.
		#' @param debug  				If \code{TRUE}, return a list with the distribution values and
		#'   per-iteration diagnostics including error messages, warning messages, counts of each,
		#'   and summary proportions for iterations with errors, warnings, and illegal (non-finite)
		#'   values. Runs serially. Default \code{FALSE}.
		#' @param bootstrap_type 		Optional bootstrap-resampling scheme; see
		#'   \code{approximate_bootstrap_distribution_beta_hat_T} for legal values. Default \code{NULL}.
		#' @param rand_bootstrap_draws 	Optional pre-generated draws (as returned by the private
		#'   method \code{generate_rand_bootstrap_draws}) enabling common random numbers across
		#'   calls with different \code{delta} values (used by the CI inversion). Default \code{NULL}.
		#' @param zero_one_logit_clamp Clamping distance from the 0/1 boundaries used by the
		#'   \code{"logit"} response transform: responses are clamped to
		#'   \code{[zero_one_logit_clamp, 1 - zero_one_logit_clamp]} before taking the logit,
		#'   so exact 0 and 1 values stay finite. Default \code{.Machine$double.eps}.
		#' @param reimpute_missing_vals_each_resample Missing covariate values in the draws.
		#'   \code{FALSE} (default): every draw analyses its rows of the design's original
		#'   imputation. \code{TRUE}: each draw's resampled rows are imputed again
		#'   (\code{missingness_method}) once, when the draw is made, and that imputation is
		#'   reused for every \code{delta} the draw is evaluated at (also the fresh assignment is
		#'   drawn on those rows), at the cost of one imputation per draw. Without missing
		#'   covariates the two are identical. Not available when the inference's covariate
		#'   matrix differs from the design's (a \code{model_formula}, or covariates dropped as
		#'   perfect predictors); a class-specific batch kernel is bypassed when it is
		#'   \code{TRUE}. See \code{compute_bootstrap_confidence_interval()}.
		#' @return 	When \code{debug = FALSE} (default), a numeric vector of length \code{B}
		#'   containing the null-distribution draws. When \code{debug = TRUE}, a list with:
		#'   \code{values}, \code{errors}, \code{warnings}, \code{num_errors}, \code{num_warnings},
		#'   \code{prop_iterations_with_errors}, \code{prop_iterations_with_warnings}, and
		#'   \code{prop_illegal_values}.
		approximate_rand_bootstrap_distribution_beta_hat_T = function(B = 501, delta = 0, transform_responses = "none", show_progress = TRUE, debug = FALSE, bootstrap_type = NULL, rand_bootstrap_draws = NULL, zero_one_logit_clamp = .Machine$double.eps, reimpute_missing_vals_each_resample = FALSE){
			# v1.0.6-TODO-131: restore the caller's operation (not NULL) so a nested call keeps an outer one.
			prev_resampling_operation = private$active_resampling_operation
			private$active_resampling_operation = "rand_bootstrap"
			on.exit(private$active_resampling_operation <- prev_resampling_operation, add = TRUE)
			# v1.0.7-TODO-190: NULL-forwarding rule of edi_bootstrap_reimpute_enter().
			prev_reimpute = edi_bootstrap_reimpute_enter(private, reimpute_missing_vals_each_resample, !missing(reimpute_missing_vals_each_resample))
			on.exit(private$cached_values$bootstrap_reimpute_active <- prev_reimpute, add = TRUE)
			reimpute = edi_bootstrap_reimputes(private)
			if (reimpute) edi_assert_bootstrap_reimpute_supported(private)
			if (!is.null(rand_bootstrap_draws) &&
			    !rand_bootstrap_smoothing_supported(self, private$des_obj_priv_int$response_type) &&
			    any(vapply(rand_bootstrap_draws, function(draw) !is.null(draw[["smooth_noise"]]), logical(1)))) {
				assert_rand_bootstrap_smoothing_supported(self, private$des_obj_priv_int$response_type)
			}
			if (should_run_asserts()) {
				private$assert_design_supports_resampling_replay("Bootstrap randomization inference")
				private$assert_valid_bootstrap_type(bootstrap_type)
				assertNumeric(delta, len = 1, finite = TRUE, any.missing = FALSE); assertCount(B, positive = TRUE); assertFlag(debug)
			}
			draws_supplied = !is.null(rand_bootstrap_draws)
			cache_key = paste(
				as.integer(B),
				formatC(as.numeric(delta), digits = 17, format = "fg", flag = "#"),
				transform_responses,
				# supplied draws already fix the scheme; fresh draws are keyed by it (v1.0.6-TODO-186)
				if (draws_supplied) attr(rand_bootstrap_draws, "draws_id")
					else paste0("fresh:", if (is.null(bootstrap_type)) "default" else bootstrap_type),
				sep = "|"
			)
			if (reimpute) cache_key = paste0(cache_key, "|reimpute")
			private$ensure_resampling_distribution_cache("rand_bootstrap")
			cached_rand_boot_distr = private$get_cached_resampling_distribution("rand_bootstrap", cache_key)
			if (!isTRUE(debug) && !is.null(cached_rand_boot_distr)) {
				return(cached_rand_boot_distr)
			}
			if (private$verbose) cat("Computing bootstrap randomization distribution...\n")
			has_custom_randomization_statistic =
				!is.null(private[["custom_randomization_statistic_function"]]) ||
				!is.null(private[["compiled_cpp_stat_fn"]])
			# A class's batch kernel resamples the fixed imputed matrix, so it cannot re-impute.
			has_fast_kernel = !reimpute && !has_custom_randomization_statistic &&
				private$has_private_method("compute_fast_rand_bootstrap_distr")
			if (draws_supplied && reimpute) rand_bootstrap_draws = edi_rand_bootstrap_attach_reimputed(private, rand_bootstrap_draws)
			if (!draws_supplied) {
				if (!is.null(private$seed)) {
					had_seed = exists(".Random.seed", envir = .GlobalEnv, inherits = FALSE)
					if (had_seed) old_seed = get(".Random.seed", envir = .GlobalEnv, inherits = FALSE)
					on.exit(
						if (had_seed) assign(".Random.seed", old_seed, envir = .GlobalEnv) else rm(".Random.seed", envir = .GlobalEnv),
						add = TRUE
					)
					set.seed(private$seed)
				}
				# The C++ batch kernel consumes pre-drawn assignment vectors, so materialize
				# them at generation time when a fast kernel is available.
				# Reusable and standard workers must evaluate the same fresh assignments.
				# Materialize them whenever the estimator supports worker reuse; otherwise
				# worker construction can consume RNG differently before drawing w.
				rand_bootstrap_draws = private$generate_rand_bootstrap_draws(
					B,
					bootstrap_type = bootstrap_type,
					materialize_w = has_fast_kernel || private$supports_reusable_bootstrap_worker()
				)
			}
			# Under the sharp null with effect delta, the control potential outcomes are the
			# observed responses with the delta shift removed from the treated subjects.
			y0_full = if (delta != 0) {
				private$shift_randomization_responses(
					y = private$y,
					w = private$w,
					delta = delta,
					transform_responses = transform_responses,
					response_type = private$des_obj_priv_int$response_type,
					inverse = TRUE,
					zero_one_logit_clamp = zero_one_logit_clamp
				)
			} else {
				private$y
			}
			if (isTRUE(debug)) {
				debug_results = lapply(rand_bootstrap_draws, function(draw) {
					iter_warns = character(0)
					iter_errs = character(0)
					iter_val = withCallingHandlers(
						tryCatch(
							private$run_rand_bootstrap_iteration(draw, delta, transform_responses, y0_full, zero_one_logit_clamp),
							error = function(e) { iter_errs <<- c(iter_errs, conditionMessage(e)); NA_real_ }
						),
						warning = function(w) { iter_warns <<- c(iter_warns, conditionMessage(w)); invokeRestart("muffleWarning") }
					)
					list(val = as.numeric(iter_val)[1L], errors = iter_errs, warnings = iter_warns)
				})
				values = vapply(debug_results, function(x) as.numeric(x[["val"]])[1L], numeric(1))
				errors_list = lapply(debug_results, `[[`, "errors")
				warnings_list = lapply(debug_results, `[[`, "warnings")
				num_errors_vec = lengths(errors_list)
				num_warnings_vec = lengths(warnings_list)
				private$set_cached_resampling_distribution("rand_bootstrap", cache_key, values)
				return(list(
					values = values,
					errors = errors_list,
					warnings = warnings_list,
					num_errors = num_errors_vec,
					num_warnings = num_warnings_vec,
					prop_iterations_with_errors = mean(num_errors_vec > 0),
					prop_iterations_with_warnings = mean(num_warnings_vec > 0),
					prop_illegal_values = mean(!is.finite(values))
				))
			}
			# Fastest path: a concrete class may provide a C++ batch kernel that evaluates the
			# whole null distribution in one call from (y0, row-index matrix, assignment matrix).
			# It returns NULL when it cannot handle the request (e.g. unmaterializable draws or
			# an unsupported transform), in which case we fall through to the standard paths.
			if (has_fast_kernel) {
				fast_distr = tryCatch(
					private$compute_fast_rand_bootstrap_distr(y0_full, rand_bootstrap_draws, delta, transform_responses, zero_one_logit_clamp),
					error = function(e) NULL
				)
				if (!is.null(fast_distr)) {
					fast_distr = as.numeric(fast_distr)
					private$set_cached_resampling_distribution("rand_bootstrap", cache_key, fast_distr)
					return(fast_distr)
				}
			}
			# Fast path: reusable worker states avoid the per-iteration design/inference
			# duplication that dominates the cost of the standard path. Custom randomization
			# statistics are excluded (compute_bootstrap_worker_estimate computes the model
			# estimate), mirroring the pure randomization test's reused-worker gating.
			if (isTRUE(private$use_reusable_bootstrap_worker()) &&
				is.null(private$custom_randomization_statistic_function) &&
				is.null(private[["compiled_cpp_stat_fn"]])) {
				t0s = private$compute_rand_bootstrap_distribution_with_reused_workers(
					rand_bootstrap_draws = rand_bootstrap_draws,
					delta = delta,
					transform_responses = transform_responses,
					y0_full = y0_full,
					actual_cores = private$effective_parallel_cores("bootstrap", self$num_cores),
					show_progress = show_progress,
					zero_one_logit_clamp = zero_one_logit_clamp
				)
				if (!is.numeric(t0s)) t0s = as.numeric(t0s)
				private$set_cached_resampling_distribution("rand_bootstrap", cache_key, t0s)
				return(t0s)
			}
			# Warm-up guard: run one iteration serially (twice, using the second timing to skip
			# cold-start penalties) and only parallelize if computation outweighs fork overhead.
			actual_cores = private$effective_parallel_cores("bootstrap", self$num_cores)
			if (actual_cores > 1L) {
				do_warmup_iter = function() {
					tryCatch(
						private$run_rand_bootstrap_iteration(rand_bootstrap_draws[[1L]], delta, transform_responses, y0_full, zero_one_logit_clamp),
						error = function(e) NA_real_
					)
				}
				system.time(do_warmup_iter())  # First call: discarded (cold-start overhead)
				t_warmup = system.time(do_warmup_iter())[[3]]  # Second call: representative cost
				fork_overhead_estimate = if (!is.null(get_global_fork_cluster())) 0.01 else 0.3
				if (!(t_warmup * B > fork_overhead_estimate * actual_cores))
					actual_cores = 1L
			}
			t0s = unlist(private$par_lapply(seq_along(rand_bootstrap_draws), function(idx) {
				tryCatch(
					suppressWarnings(private$run_rand_bootstrap_iteration(rand_bootstrap_draws[[idx]], delta, transform_responses, y0_full, zero_one_logit_clamp)),
					error = function(e) NA_real_
				)
			}, n_cores = actual_cores, show_progress = show_progress,
			export_list = list(
				rand_bootstrap_draws = rand_bootstrap_draws,
				delta = delta,
				transform_responses = transform_responses,
				y0_full = y0_full,
				zero_one_logit_clamp = zero_one_logit_clamp
			)))
			if (!is.numeric(t0s)) t0s = as.numeric(t0s)
			private$set_cached_resampling_distribution("rand_bootstrap", cache_key, t0s)
			t0s
		},
		#' @description Computes a bootstrap randomization two-sided p-value for Fisher's sharp
		#'   null (shifted by \code{delta}): the observed statistic (actual data, actual \code{w})
		#'   is compared against the null distribution generated by resampling rows and drawing
		#'   fresh assignments from the design.
		#'
		#' @param B  					Number of bootstrap randomization draws. Default 501.
		#' @param delta  				The sharp-null shift of the responses (on the
		#'   \code{transform_responses} scale), not a value of the estimand. Default 0, the null
		#'   of no effect for every class, including ratio estimands (risk ratio 1, log risk ratio
		#'   0); the studentized types center their pivot at the estimand's no-effect value (1 for
		#'   the raw risk-ratio g-computation classes).
		#' @param transform_responses  Type of response transformation for the sharp null shift.
		#'   The default "none" resolves by response type (logit for proportion, log for count
		#'   and survival, identity otherwise), matching \code{compute_rand_two_sided_pval}.
		#' @param na.rm 				Remove non-finite null draws. Default \code{TRUE}, subject to
		#'   \code{min_fraction_usable_samples}. With \code{FALSE}, any non-finite null draw (for
		#'   the studentized types: also a missing or non-positive draw standard error) makes the
		#'   p-value \code{NA}, with one \code{edi_bootstrap_nonfinite_na_warning} per object
		#'   (silent inside an outer resampling operation). Under the sequential Monte Carlo
		#'   early-stopping path (\code{brt_mc_control}) only the draws evaluated before stopping
		#'   are checked. With \code{TRUE} that path applies \code{min_fraction_usable_samples}
		#'   (see there).
		#' @param min_fraction_usable_samples Minimum fraction of the null draws that must be
		#'   finite when \code{na.rm = TRUE} (for the studentized types: a finite statistic and a
		#'   positive finite standard error). A number in \eqn{[0, 1]}; default \code{0.95},
		#'   which mirrors the 5\% cap on invalid intervals that EDI's coverage calibration
		#'   applies to confidence intervals. Below it the p-value is \code{NA} with the recorded
		#'   reason \code{"rand_bootstrap_too_few_valid_replicates_fraction"} and one
		#'   \code{edi_procedure_na_warning} (silent inside an outer resampling operation). Fewer
		#'   than \code{max(10, 10\%)} finite draws keep the existing reason
		#'   \code{"randomization_too_few_finite_estimates"}. \code{0} turns the check off;
		#'   \code{1} requires every draw. The sequential Monte Carlo early-stopping path
		#'   (\code{brt_mc_control}) does not stop on a prefix of the draws with too few valid
		#'   draws: it draws the next batch, and applies the check to all \code{B} draws when it
		#'   gets there (v1.0.6-TODO-160). A prefix that clears the check can still stop early,
		#'   so a run that stops early never sees the later draws. Not applied inside
		#'   \code{compute_rand_bootstrap_confidence_interval()}, which inverts these p-values
		#'   and has its own failure reasons.
		#' @param show_progress  		A flag indicating whether a progress bar should be displayed.
		#' @param bootstrap_type 		Optional bootstrap-resampling scheme; see
		#'   \code{approximate_bootstrap_distribution_beta_hat_T} for legal values. Default \code{NULL}.
		#' @param rand_bootstrap_draws 	Optional pre-generated draws for common random numbers
		#'   across \code{delta} values. Default \code{NULL}.
		#' @param zero_one_logit_clamp Clamping distance from the 0/1 boundaries used by the
		#'   \code{"logit"} response transform: responses are clamped to
		#'   \code{[zero_one_logit_clamp, 1 - zero_one_logit_clamp]} before taking the logit,
		#'   so exact 0 and 1 values stay finite. Default \code{.Machine$double.eps}.
		#' @param type  				Test statistic type. \code{"percentile"} (default) uses the raw
		#'   estimator as the BRT test statistic, giving an asymptotic p-value that inherits
		#'   the unconditional superpopulation validity of the BRT.
		#'   \code{"studentized"} divides each null draw's signed deviation from the null by its
		#'   per-draw standard error and doubles the smaller tail of
		#'   \eqn{z^0_b = (t^0_b - \delta)/\hat{s}^0_b}; yields asymmetric CI under inversion.
		#'   \code{"symmetric-percentile-t"} uses the absolute pivot: it counts the draws with
		#'   \eqn{|t^0_b - \delta|/\hat{s}^0_b \ge |t - \delta|/\hat{s}}, no doubling; CI is symmetric.
		#'   Every type counts the observed statistic as one of the \eqn{B} finite draws
		#'   (v1.2.0-TODO-207, Phipson and Smyth 2010): the doubled-tail types
		#'   (\code{"percentile"}, \code{"smoothed"}, \code{"studentized"}) return
		#'   \eqn{\min(1, 2(1 + \min(b_{\ge}, b_{\le}))/(1 + B))}{min(1, 2 (1 + min(b_ge, b_le)) / (1 + B))}
		#'   (smallest \eqn{2/(B + 1)}), and \code{"symmetric-percentile-t"} returns
		#'   \eqn{(1 + b_{|\cdot|})/(1 + B)}{(1 + b_abs) / (1 + B)}, where \eqn{b_{|\cdot|}}{b_abs}
		#'   counts the draws with an absolute pivot at least as large (smallest \eqn{1/(B + 1)}).
		#'   Neither is ever 0.
		#'   Both SE-based types require the class to expose \code{s_beta_hat_T}; fall back to
		#'   \code{"percentile"} if the SE is unavailable.
		#'   \code{"smoothed"} is refused (with an error) for left- or interval-censored survival
		#'   responses: censored subjects have no exact time to smooth (v1.0.6-TODO-98); use
		#'   \code{"percentile"} there.
		#'   \code{"smoothed"} adds kernel noise \eqn{\varepsilon_b \sim N(0, \hat{\sigma}/\sqrt{n})}
		#'   to each resampled draw before imposing the null shift, reducing discreteness in the
		#'   null distribution. Supported for real-valued statistics on coded responses and
		#'   for continuous, count, and survival responses. Categorical or bounded model
		#'   refits and ordinal Ridit/Jonckheere-Terpstra estimators reject this type because Gaussian noise
		#'   leaves their response support. For count responses the noisy draw is rounded and
		#'   floored at zero so it stays on the non-negative integer support the Poisson-family
		#'   likelihoods require; at the default bandwidth this makes smoothing nearly a no-op
		#'   for low counts.
		#'
		#'   \strong{Theoretical justification.} Order-statistic/rank-based estimators (e.g. the
		#'   Hodges-Lehmann pseudo-median) take only finitely many values, so their bootstrap/
		#'   randomization null distribution is a step function; this both coarsens p-values and
		#'   destabilizes the \code{uniroot}-based \code{delta} search in
		#'   \code{\link{InferenceRandBootstrapCI}}'s \code{compute_rand_bootstrap_confidence_interval},
		#'   which assumes an approximately continuous, monotone p-value curve. Restoring continuity
		#'   by convolving the resampling distribution with a shrinking-bandwidth kernel is the
		#'   classical "smoothed bootstrap" device: Silverman (1981, "Density ratios, empirical
		#'   likelihood and cot death", \emph{Applied Statistics} 30(2):142-145) for kernel smoothing
		#'   of a resampled empirical distribution; Silverman & Young (1987, "The bootstrap: To
		#'   smooth or not to smooth?", \emph{Biometrika} 74(3):469-479) for applying that smoothing
		#'   directly to the bootstrap resampling scheme; and Hall, DiCiccio & Romano (1989, "On
		#'   smoothing and the bootstrap", \emph{Annals of Statistics} 17(2):692-704) for the
		#'   bandwidth conditions under which smoothing improves, rather than degrades, coverage
		#'   accuracy.
		#'
		#'   \strong{Implementation caveat (ad hoc, not a certified instance of the above).} The
		#'   bandwidth used here, \eqn{\hat{\sigma}/\sqrt{n}} (the raw SE-of-the-mean scale of the
		#'   response), is a pragmatic engineering choice, not one derived from or validated against
		#'   the bandwidth-selection results in the sources above. Those references smooth the
		#'   \emph{resampling distribution itself} with a bandwidth chosen to trade off bias against
		#'   variance (often shrinking slower than \eqn{n^{-1/2}}, e.g. \eqn{n^{-1/5}}-type
		#'   KDE rates); here, noise is instead added directly to each already-resampled response at
		#'   a fixed \eqn{n^{-1/2}} rate. The bandwidth is not exposed as a parameter and has no
		#'   zero-noise escape hatch (the only way to disable smoothing is to pick a different
		#'   \code{type}). Treat it as a discreteness patch that is qualitatively motivated by the
		#'   literature above, not a certified implementation of it. A true-null simulation (nine
		#'   continuous and count classes, \code{n = 148}, \code{B = 101}, at least 500 data sets
		#'   each, smoothed and percentile p-values computed on the same draws) found the two
		#'   rejecting at the same rate in every class, so smoothing does not change the test's size.
		#'
		#'   \strong{Limitation: many covariates per observation.} The \code{"percentile"} and
		#'   \code{"smoothed"} types use the unstudentized estimator, so their null distribution is
		#'   only as wide as the refits on resampled rows make it. A resample of \code{n} rows holds
		#'   only about \eqn{0.63 n} distinct ones, so when the model has many covariates relative
		#'   to \code{n} each refit overfits and the null distribution comes out too narrow, which
		#'   makes the test anti-conservative. In the simulation above, \code{InferenceContinOLS}
		#'   with \code{model_formula = ~ .} (24 columns at \code{n = 148}) rejected 13-14\% at
		#'   nominal 5\% (the null spread was about 0.71 of the true sampling spread), and
		#'   \code{InferenceCountPoisson} with \code{~ .} rejected 7.6\%; with \code{~ 1} or few
		#'   covariates both were nominal, and OLS's Wald test on the same data rejected 4.2\%. Small
		#'   samples show a milder version of the same effect. With many covariates, prefer
		#'   \code{type = "studentized"} where the class supports it, a smaller
		#'   \code{model_formula}, or the class's model-based or randomization (\code{compute_rand_*})
		#'   tests.
		#'
		#'   \strong{Performance.} Every class with a C++ \code{compute_fast_rand_bootstrap_distr}
		#'   kernel that operates on real-valued responses (Wilcox HL, simple mean difference, OLS,
		#'   robust regression, CoxPH, Weibull marginal, log-rank, RMST, KM-diff) accepts the smoothing
		#'   noise directly in its kernel. This only speeds up \code{\link{InferenceRandBootstrapCI}}'s
		#'   \code{compute_rand_bootstrap_confidence_interval(type = "smoothed")}, since CI inversion
		#'   pre-materializes one set of fresh assignments up front (common random numbers reused
		#'   across every \code{delta} evaluated during root-finding) and the fast kernel can engage on
		#'   each evaluation; measured on \code{InferenceAllSimpleWilcox}, \code{n = 30}, \code{B = 99}:
		#'   the forced-slow-fallback CI took 25.5s, the fast-kernel CI took 0.5s (about 50x). A
		#'   \emph{standalone} \code{compute_rand_bootstrap_two_sided_pval(type = "smoothed")} call
		#'   (no CI inversion) is \strong{not} accelerated by this: it deliberately draws the fresh
		#'   assignment lazily per replicate (\code{materialize_w = FALSE}), so
		#'   \code{rand_bootstrap_draw_matrices()} cannot build the matrices the fast kernels need and
		#'   the R-level fallback still runs regardless of this fix. The two ordinal classes
		#'   (\code{InferenceOrdinalRidit}, \code{InferenceOrdinalJonckheereTerpstraTest}) still use the
		#'   slower R-level fallback in every case, because adding continuous Gaussian noise to integer
		#'   category codes is not statistically meaningful — see the response-type caveat above.
		#' @param reimpute_missing_vals_each_resample Missing covariate values in the draws.
		#'   \code{FALSE} (default): every draw analyses its rows of the design's original
		#'   imputation. \code{TRUE}: each draw's resampled rows are imputed again
		#'   (\code{missingness_method}) once, when the draw is made, and that imputation is
		#'   reused for every \code{delta} the draw is evaluated at (also the fresh assignment is
		#'   drawn on those rows), at the cost of one imputation per draw. Without missing
		#'   covariates the two are identical. Not available when the inference's covariate
		#'   matrix differs from the design's (a \code{model_formula}, or covariates dropped as
		#'   perfect predictors); a class-specific batch kernel is bypassed when it is
		#'   \code{TRUE}. See \code{compute_bootstrap_confidence_interval()}.
		#' @return 	A two-sided p-value.
		compute_rand_bootstrap_two_sided_pval = function(B = 501, delta = 0, transform_responses = "none", na.rm = TRUE, show_progress = TRUE, bootstrap_type = NULL, rand_bootstrap_draws = NULL, zero_one_logit_clamp = .Machine$double.eps, type = "percentile", min_fraction_usable_samples = 0.95, reimpute_missing_vals_each_resample = FALSE){
			if (identical(tolower(type), "smoothed")) assert_rand_bootstrap_smoothing_supported(self, private$des_obj_priv_int$response_type)
			# v1.0.7-TODO-190: the methods this one calls inherit the setting (they are called
			# without the argument). Supplied draws get their once-per-draw imputation here, so
			# every branch below (studentized, smoothed, sequential, plain) uses it.
			prev_reimpute = edi_bootstrap_reimpute_enter(private, reimpute_missing_vals_each_resample, !missing(reimpute_missing_vals_each_resample))
			on.exit(private$cached_values$bootstrap_reimpute_active <- prev_reimpute, add = TRUE)
			if (edi_bootstrap_reimputes(private)) {
				edi_assert_bootstrap_reimpute_supported(private)
				if (!is.null(rand_bootstrap_draws)) rand_bootstrap_draws = edi_rand_bootstrap_attach_reimputed(private, rand_bootstrap_draws)
			}
			# v1.0.6-TODO-102: same incidence guard as compute_rand_two_sided_pval()
			# (v1.0.6-TODO-42 / v1.0.6-TODO-64). A nonzero delta shifted the 0/1 responses additively
			# (e.g. to 0.2/1.2), which is no sharp null on any scale, and a risk-ratio
			# class's delta = 1.2 was silently that shift, not the null RR = 1.2.
			if (isTRUE(delta != 0) &&
					private$des_obj_priv_int$response_type == "incidence") {
				stop("bootstrap randomization tests with delta nonzero not supported for incidence", call. = FALSE)
			}
			if (should_run_asserts()) {
				private$assert_design_supports_resampling_replay("Bootstrap randomization inference")
				assertNumeric(delta, len = 1, finite = TRUE, any.missing = FALSE); assertCount(B, positive = TRUE); assertFlag(na.rm)
				assertChoice(tolower(type), private$rand_bootstrap_pval_types)
				assert_min_fraction_usable_samples(min_fraction_usable_samples)
			}
			# v1.0.6-TODO-2: with na.rm = TRUE the p-value needs min_fraction_usable_samples of
			# the null draws to be valid. TRUE (after recording the reason and warning) when it
			# falls short. A run below the randomization floor of
			# compute_two_sided_randomization_pval_from_t0s() (max(10, 10%)) is left to that
			# floor, so its reason "randomization_too_few_finite_estimates" is unchanged.
			brt_valid_fraction_short = function(n_valid, n_total, what = "null-distribution draws") {
				if (!isTRUE(na.rm) || n_valid < max(10L, as.integer(n_total * 0.10))) return(FALSE)
				if (!bootstrap_valid_fraction_too_low(n_valid, n_total, min_fraction_usable_samples)) return(FALSE)
				if (isTRUE(private$harden)) edi_record_procedure_failure(self, private, "rand_bootstrap_too_few_valid_replicates_fraction", "estimate")
				edi_warn_procedure_na(self, private, procedure = "randomization-bootstrap p-value",
					reason = "rand_bootstrap_too_few_valid_replicates_fraction",
					detail = bootstrap_valid_fraction_na_detail(n_valid, n_total, min_fraction_usable_samples, what = what))
				TRUE
			}
			# v1.0.6-TODO-155: na.rm = FALSE returns NA on any invalid null draw, on every path
			# (percentile, smoothed, studentized, sequential Monte Carlo), with one classed
			# edi_bootstrap_nonfinite_na_warning per object, as the other bootstrap p-values do.
			brt_na_rm_false_na = function(t0s, valid = is.finite(t0s)) {
				if (isTRUE(na.rm) || all(valid)) return(FALSE)
				edi_warn_bootstrap_nonfinite_na_once(self, private, t0s, fn = "compute_rand_bootstrap_two_sided_pval",
					rand_bootstrap = TRUE, valid = valid)
				TRUE
			}
			if (identical(transform_responses, "none")) {
				transform_responses = switch(
					private$des_obj_priv_int$response_type,
					continuous = "none",
					proportion = "logit",
					count = "log",
					survival = "log",
					"none"
				)
			}
			t = private$compute_treatment_estimate_during_randomization_inference()
			if (is.function(self$is_nonestimable) && isTRUE(self$is_nonestimable("estimate"))) return(NA_real_)
			if (is.list(t) && "b" %in% names(t)) t = t$b[1]
			t = as.numeric(t)[1]
			if (length(t) != 1 || !is.finite(t)) {
				if (isTRUE(private$harden)) edi_record_procedure_failure(self, private, "rand_bootstrap_observed_statistic_unavailable", "estimate")
				return(NA_real_)
			}
			type_lc = tolower(type)
			# Studentized / symmetric-percentile-t BRT p-value: pivot each null draw by its per-draw SE.
			# "studentized" uses signed pivots (asymmetric); "symmetric-percentile-t" uses |pivot|.
			# Falls back to "percentile" when the SE is unavailable.
			if (type_lc %in% c("studentized", "symmetric-percentile-t")) {
				y0_full_stud = if (delta != 0) {
					private$shift_randomization_responses(
						y = private$y, w = private$w, delta = delta,
						transform_responses = transform_responses,
						response_type = private$des_obj_priv_int$response_type,
						inverse = TRUE, zero_one_logit_clamp = zero_one_logit_clamp
					)
				} else {
					private$y
				}
				draws_stud = if (!is.null(rand_bootstrap_draws)) {
					rand_bootstrap_draws
				} else {
					if (!is.null(private$seed)) {
						had_seed_st = exists(".Random.seed", envir = .GlobalEnv, inherits = FALSE)
						if (had_seed_st) old_seed_st = get(".Random.seed", envir = .GlobalEnv, inherits = FALSE)
						on.exit(
							if (had_seed_st) assign(".Random.seed", old_seed_st, envir = .GlobalEnv) else if (exists(".Random.seed", envir = .GlobalEnv, inherits = FALSE)) rm(".Random.seed", envir = .GlobalEnv),
							add = TRUE
						)
						set.seed(private$seed)
					}
					private$generate_rand_bootstrap_draws(B, bootstrap_type = bootstrap_type, materialize_w = TRUE)
				}
				brt_stats = private$compute_brt_null_statistics_with_se(
					draws_stud, delta, transform_responses, y0_full_stud, zero_one_logit_clamp
				)
				se_obs_stud = tryCatch(private$infer_original_se(), error = function(e) NA_real_)
				if (!is.finite(se_obs_stud) || se_obs_stud <= 0) {
					# SE unavailable: fall through to percentile
				} else {
					symmetric_pivot = identical(type_lc, "symmetric-percentile-t")
					# v1.0.6-TODO-102: `delta` is the sharp-null shift on the response scale, and
					# delta = 0 (no effect) is the only value allowed for incidence. The pivot must be
					# centered at the matching null of the estimand; that is delta itself except for
					# the raw risk-ratio g-computation classes, whose estimate is RR and whose
					# no-effect null is RR = 1 (`default_null_value()`; 0 for their RD siblings).
					stud_center = delta
					if (identical(as.numeric(delta), 0) && private$has_private_method("default_null_value")) {
						stud_center = private$default_null_value()
					}
					ok_stud = is.finite(brt_stats$t0) & is.finite(brt_stats$se0) & brt_stats$se0 > 0
					if (brt_na_rm_false_na(brt_stats$t0, valid = ok_stud)) return(NA_real_)
					n_ok_stud = sum(ok_stud)
					if (brt_valid_fraction_short(n_ok_stud, length(brt_stats$t0), what = "null draws (statistic and standard error)")) return(NA_real_)
					return(private$compute_two_sided_brt_pval_studentized(t, brt_stats$t0, brt_stats$se0, stud_center, se_obs_stud, symmetric = symmetric_pivot))
				}
			}
			# Smoothed BRT p-value: kernel noise per draw reduces null-distribution discreteness.
			# Noise is pre-generated once per draw and reused across delta evaluations (CRN).
			if (identical(type_lc, "smoothed")) {
				draws_sm = if (!is.null(rand_bootstrap_draws) && !is.null(rand_bootstrap_draws[[1L]][["smooth_noise"]])) {
					rand_bootstrap_draws  # noise already added (e.g., by CI inversion loop)
				} else {
					d = if (!is.null(rand_bootstrap_draws)) {
						rand_bootstrap_draws
					} else {
						if (!is.null(private$seed)) {
							had_seed_sm = exists(".Random.seed", envir = .GlobalEnv, inherits = FALSE)
							if (had_seed_sm) old_seed_sm = get(".Random.seed", envir = .GlobalEnv, inherits = FALSE)
							on.exit(
								if (had_seed_sm) assign(".Random.seed", old_seed_sm, envir = .GlobalEnv) else if (exists(".Random.seed", envir = .GlobalEnv, inherits = FALSE)) rm(".Random.seed", envir = .GlobalEnv),
								add = TRUE
							)
							set.seed(private$seed)
						}
						private$generate_rand_bootstrap_draws(B, bootstrap_type = bootstrap_type, materialize_w = FALSE)
					}
					n_int = as.integer(private$n)
					sd_y = stats::sd(private$y, na.rm = TRUE)
					if (!is.finite(sd_y) || sd_y <= 0) sd_y = 1.0
					bw = sd_y / sqrt(n_int)
					for (b in seq_along(d)) d[[b]][["smooth_noise"]] = stats::rnorm(n_int, 0, bw)
					attr(d, "draws_id") = paste0(attr(d, "draws_id"), "_smoothed")
					d
				}
				t0s_sm = self$approximate_rand_bootstrap_distribution_beta_hat_T(
					B = B, delta = delta, transform_responses = transform_responses,
					show_progress = FALSE, rand_bootstrap_draws = draws_sm,
					zero_one_logit_clamp = zero_one_logit_clamp
				)
				if (brt_na_rm_false_na(t0s_sm)) return(NA_real_)
				if (brt_valid_fraction_short(sum(is.finite(t0s_sm)), length(t0s_sm))) return(NA_real_)
				return(private$compute_two_sided_randomization_pval_from_t0s(t0s_sm, t, procedure = "randomization-bootstrap p-value"))
			}
			# SMC early-stopping: evaluate the null distribution in batches; stop once the
			# Clopper-Pearson 99% band around the p-value clears the mc_stop_threshold on
			# one side. Activated by brt_mc_control (set by CI inversion or the user).
			mc_ctrl = private$brt_mc_control
			if (!is.null(mc_ctrl) && isTRUE(mc_ctrl$mc_enable) && isTRUE(is.finite(mc_ctrl$mc_stop_threshold))) {
				# Ensure w_b is materialized so the prefix cache gives consistent per-draw values.
				if (is.null(rand_bootstrap_draws)) {
					if (!is.null(private$seed)) {
						had_seed_smc = exists(".Random.seed", envir = .GlobalEnv, inherits = FALSE)
						if (had_seed_smc) old_seed_smc = get(".Random.seed", envir = .GlobalEnv, inherits = FALSE)
						on.exit(
